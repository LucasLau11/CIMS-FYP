"""
Writes lib/utils/known_terms.dart: the words of the skills vocabulary, so the app's resume parser can tell
that "Python Java" or "Microsoft Office" is a list of skills and not somebody's name.

    python gen_known_terms.py

Run it again after editing skills_vocabulary.py. (nlp_service/extractor.py imports the same vocabulary directly.)
"""

import os
import re

from skills_vocabulary import ALL_SKILLS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "lib", "utils", "known_terms.dart")

EXTRA = ["programming", "software", "developer", "hardware", "database", "networking", "frontend", "backend", "fullstack",
         "multimedia", "analytics", "spreadsheet", "internet", "cloud"]


def tokens(skills):
    out = set()
    for s in skills:
        for w in re.findall(r"[A-Za-z][A-Za-z+#.]*", s):
            w = w.lower().strip(".")
            # short words ("go", "r", "c", "ml", "ai") are also ordinary names: leave them out
            if len(w) >= 4:
                out.add(w)
    return sorted(out | set(EXTRA))


def main() -> None:
    words = tokens(ALL_SKILLS)
    phrases = sorted({s.lower() for s in ALL_SKILLS})
    lines = [
        "// GENERATED by nlp_service/gen_known_terms.py from skills_vocabulary.py. Do not edit by hand.",
        "",
        "/// Words (four letters or more) that appear in skill names: a line made of them is a list of skills.",
        "const Set<String> kSkillWords = {",
    ]
    lines += [f"  '{w}'," for w in words]
    lines += ["};", "", "/// Whole skill names, lower case.", "const Set<String> kSkillPhrases = {"]
    lines += ["  '" + p.replace("'", "\\'") + "'," for p in phrases]
    lines += ["};", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(words)} words and {len(phrases)} phrases -> {OUT}")


if __name__ == "__main__":
    main()
