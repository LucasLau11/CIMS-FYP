# Words that mark a line as a heading even when its exact wording is not in the list above ("AWARDS, HONOURS &
# CO-CURRICULAR"); used only for lines written in capitals or ending in ":". The strong ones are never a skill;
# the weak ones ("PROJECT MANAGEMENT", "LANGUAGES") are checked against the skills vocabulary first.
_HEADING_STEM_STRONG = re.compile(
    r"\b(?:referees?|references?|activities|achievements?|awards?|honou?rs?|declaration|particulars|volunteer\w*|curricular|"
    r"scholarships?|publications?|hobbies|biodata|education|experience)\b", re.IGNORECASE)
_HEADING_STEM_WEAK = re.compile(r"\b(?:projects?|certifications?|certificates?|interests?|languages?)\b", re.IGNORECASE)

# a page number / footer that a PDF puts into the text: "Page 1 of 2", "— 1 —"
_PAGE_FOOTER = re.compile(r"^(?:page\s+\d+(?:\s*(?:of|/)\s*\d+)?|[—–-]+\s*\d+\s*[—–-]+)$", re.IGNORECASE)


def _heading_key(line: str) -> str:
    return re.sub(r"[:\-–—]+$", "", line.strip().lower()).strip()


def _is_heading_line(raw: str) -> bool:
    """A known heading, or a short line in capitals / ending in ':' that contains a heading word."""
    t = raw.strip()
    key = _heading_key(t)
    if not key or len(key) > 45:
        return False
    if len(key) <= 40 and key in ALL_SECTION_HEADINGS:
        return True
    if len(t.split()) > 7:
        return False
    shouty = t == t.upper() and re.search(r"[A-Z]", t) is not None
    if not shouty and not t.endswith(":"):
        return False
    if _HEADING_STEM_STRONG.search(key):
        return True
    if any(w in SKILL_WORDS for w in re.split(r"[^a-z+#.]+", key) if w):
        return False
    return _HEADING_STEM_WEAK.search(key) is not None


def _extract_sections(text: str, heading_aliases: list[str]) -> list[list[str]]:
    """Every section whose heading is one of the aliases: the lines after each heading, up to the next
    recognised heading. Empty when no heading appears as a standalone line."""
    lines = text.split("\n")
    blocks: list[list[str]] = []
    for i, raw in enumerate(lines):
        cleaned = _heading_key(raw)
        if not cleaned or len(cleaned) > 40 or cleaned not in heading_aliases:
            continue
        collected: list[str] = []
        for j in range(i + 1, len(lines)):
            if _is_heading_line(lines[j]):
                break
            if _PAGE_FOOTER.match(lines[j].strip()):
                continue
            collected.append(lines[j])
            if len(collected) >= 40:
                break
        blocks.append(collected)
    return blocks


_INLINE_SKILLS = re.compile(
    r"^\s*(?:" + "|".join(re.escape(h) for h in sorted(SKILLS_HEADINGS, key=len, reverse=True)) + r")\s*:\s*(.+)$",
    re.IGNORECASE | re.MULTILINE,
)

# short abbreviations joined by a slash that are ONE skill ("CI/CD", "UI/UX", "TCP/IP")
_SLASH_COMPOUND = re.compile(r"^[A-Z0-9+#.]{1,6}/[A-Z0-9+#.]{1,6}$")

# a proficiency level after a skill: "Python (Advanced)", "SQL - Intermediate", "Java (3 years)"
_SKILL_LEVEL = re.compile(
    r"\s*(?:[\(\[]\s*(?:advanced|intermediate|beginner|basic|proficient|expert|fluent|familiar|good|native|\d+\+?\s*(?:years?|yrs?))[^\)\]]*[\)\]]"
    r"|[\-–—:]\s*(?:advanced|intermediate|beginner|basic|proficient|expert|fluent|familiar|good))\s*$",
    re.IGNORECASE,
)


_JUNK_SKILL_A = re.compile(
    r"@|https?:|www\.|linkedin|github\.com|\d{5,}|upon request|references? (?:are )?(?:available|provided)|\b(?:tel|phone|mobile|email|address)\b",
    re.IGNORECASE)
_JUNK_SKILL_B = re.compile(r"^(?:Mr|Mrs|Ms|Miss|Dr|Prof|Encik|Puan|Cik|Tuan|Datin|Dato)\.?\s+[A-Z][a-z]")


def _junk_skill(token: str) -> bool:
    """True when `token` cannot be a skill: contact details, a referee ("Dr. Ahmad, Senior Lecturer"), a sentence."""
    if _JUNK_SKILL_A.search(token) or _JUNK_SKILL_B.match(token):
        return True
    return len(token.split()) > 5


def _extract_skills(text: str) -> list[str]:
    # "Skills: Python, Java, SQL" on ONE line, as well as every heading with a list under it
    block_lines = list(_INLINE_SKILLS.findall(text))
    for block in _extract_sections(text, SKILLS_HEADINGS):
        block_lines += block
    if not block_lines:
        return []

    tokens: list[str] = []
    seen: set[str] = set()
    for raw_line in block_lines:
        line = re.sub(r"^[•▪◦·●○■*\-]\s+", "", raw_line.strip())
        if not line:
            continue
        for part in re.split(r"[,;|]|\s{2,}", line):
            cleaned = re.sub(r"^[•▪◦·●○■*]+|[.]+$", "", part.strip()).strip()
            cleaned = re.sub(r"^[A-Za-z][A-Za-z &/]{2,24}:\s*", "", cleaned)  # "Programming: Python" -> "Python"
            cleaned = _SKILL_LEVEL.sub("", cleaned).strip()
            pieces = re.split(r"\s*/\s*", cleaned) if "/" in cleaned and not _SLASH_COMPOUND.match(cleaned) else [cleaned]
            for piece in pieces:
                token = _SKILL_LEVEL.sub("", piece.strip()).strip()
                if not token or len(token) > 30:
                    continue
                if not re.search(r"[A-Za-z]", token):
                    continue
                if _junk_skill(token):  # an email, a phone, a referee's name, "available upon request"...
                    continue
                key = token.lower()
                if key not in seen:
                    seen.add(key)
                    tokens.append(token)
        if len(tokens) >= 40:
            break
    return tokens


_STREET_KEYWORDS = re.compile(
    r"\b(jalan|jln|lorong|lrg|taman|tmn|persiaran|lot|no\.?\s?\d|blok|unit|apartment|kondominium|street|avenue|road|drive|boulevard)\b",
    re.IGNORECASE,
)


def _looks_like_a_place_not_a_name(candidate: str) -> bool:
    """Pretrained NER occasionally tags a short street/place name (e.g.
    "Jalan Ampang") as PERSON — it superficially looks like a two-word
    proper noun. Reject anything matching known address vocabulary before
    trusting an NLP-found name."""
    return bool(_STREET_KEYWORDS.search(candidate))


_MONTH = r"(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?"

# "Jun 2022 - Aug 2022", "2022 – Present", "January 2021 to December 2022", "2020-2021"
# and months inside one year: "Jun – Aug 2024"
_DATE_RANGE_PATTERN = re.compile(
    rf"(?:({_MONTH})\s+)?(\d{{4}})\s*(?:-|–|—|to)\s*(?:({_MONTH})\s+)?(present|current|now|\d{{4}})"
    rf"|({_MONTH})\s*(?:-|–|—|to)\s*({_MONTH})\s+(\d{{4}})",
    re.IGNORECASE,
)

_BULLET_START = re.compile(r"^[•▪◦·●○■*\-]\s*")


def _org_entities_in(doc_span_text: str) -> list[str]:
    """Pretrained-NER enrichment: ORG entities found within one job entry's
    text, used as a cross-check/fallback for the regex-split company name."""
    doc = _nlp(doc_span_text)
    return [ent.text.strip() for ent in doc.ents if ent.label_ == "ORG"]


def _split_title(title: str) -> tuple[Optional[str], Optional[str]]:
    """"Position, Company" / "Position at Company" / "Position | Company" / "Position - Company"."""
    m = re.match(r"^(.*?)(?:\s+(?:at|@|-|–|—|\|)\s+|\s*,\s+)(.*)$", title)
    if not m:
        return title, None
    return m.group(1).strip() or None, m.group(2).strip() or None


def _extract_work_experience(text: str) -> list[ParsedWorkExperience]:
    entries: list[ParsedWorkExperience] = []
    for block in _extract_sections(text, WORK_HEADINGS):
        entries += _work_entries_of(block)
        if len(entries) >= 8:
            break
    return entries[:8]


def _work_entries_of(block_lines: list[str]) -> list[ParsedWorkExperience]:
    if not block_lines:
        return []

    anchor_indexes = [i for i, line in enumerate(block_lines) if _DATE_RANGE_PATTERN.search(line)]
    if not anchor_indexes:
        non_empty = [l.strip() for l in block_lines if l.strip()]
        if not non_empty:
            return []
        return [
            ParsedWorkExperience(
                position=non_empty[0] if len(non_empty[0]) <= 60 else None,
                description="\n".join(non_empty),
            )
        ]

    entries: list[ParsedWorkExperience] = []
    for a, anchor_line in enumerate(anchor_indexes):
        if len(entries) >= 8:
            break
        next_anchor = anchor_indexes[a + 1] if a + 1 < len(anchor_indexes) else len(block_lines)

        date_match = _DATE_RANGE_PATTERN.search(block_lines[anchor_line])
        if date_match.group(7):
            start_year = end_year = int(date_match.group(7))  # "Jun – Aug 2024": one year
            is_current = False
        else:
            start_year = int(date_match.group(2)) if date_match.group(2) else None
            end_raw = date_match.group(4)
            is_current = bool(re.match(r"present|current|now", end_raw, re.IGNORECASE))
            end_year = None if is_current else (int(end_raw) if end_raw.isdigit() else None)

        line = block_lines[anchor_line]
        date_stripped = line[: date_match.start()] + " " + line[date_match.end() :]
        date_stripped = re.sub(r"[()\[\]]", " ", date_stripped)
        date_stripped = _BULLET_START.sub("", date_stripped.strip())
        date_stripped = re.sub(r"^[\s:,;|\-–—]+|[\s:,;|\-–—]+$", "", date_stripped)
        date_stripped = re.sub(r"\s{2,}", " ", date_stripped).strip()

        position: Optional[str] = None
        company: Optional[str] = None
        if not date_stripped:
            # the date was on its own line: the title is the line just before it
            prev = _BULLET_START.sub("", block_lines[anchor_line - 1].strip()) if anchor_line > 0 else ""
            if prev:
                position, company = _split_title(prev)
        else:
            position, company = _split_title(date_stripped)
            if company is None:
                # "Position" on one line, "Company, dates" on the next
                prev = None
                for k in range(anchor_line - 1, -1, -1):
                    candidate = block_lines[k].strip()
                    if candidate:
                        prev = candidate
                        break
                if (
                    prev
                    and not _BULLET_START.match(prev)
                    and not _DATE_RANGE_PATTERN.search(prev)
                    and len(prev) <= 80
                    and not prev.endswith(".")
                ):
                    company = date_stripped
                    position = prev

        description_lines = []
        for i in range(anchor_line + 1, next_anchor):
            l = block_lines[i].strip()
            if not l:
                continue
            description_lines.append(re.sub(r"^[•▪◦·●○■*\-]\s*", "", l))
        description = "\n".join(description_lines) if description_lines else None

        # Pretrained-NER cross-check: if regex didn't split out a company
        # name, see if spaCy found an ORG entity on the title line itself.
        if not company and date_stripped:
            orgs = _org_entities_in(date_stripped)
            if orgs:
                company = orgs[0]

        if position or company or description:
            entries.append(
                ParsedWorkExperience(
                    position=position or None,
                    companyName=company or None,
                    startYear=start_year,
                    endYear=end_year,
                    isCurrent=is_current,
                    description=description,
                )
            )
    return entries


def _extract_labelled(text: str, labels: list[str]) -> Optional[str]:
    """The value after one of the labels ("Phone: 012...", "Address - ...", "Tel" + next line). The label
    must not be the tail of a longer word ("hotel:" is not "tel:"), "Email Address:" is not "Address:",
    and a label alone on its line takes the next non-empty line as its value."""
    lines = text.split("\n")
    for label in labels:
        escaped = re.escape(label)
        match = re.search(rf"(?<![A-Za-z])(?<!mail )(?<!mail\t){escaped}\s*[:\-–]\s*(.+)", text, re.IGNORECASE)
        if match:
            value = match.group(1).strip()
            if value and len(value) < 150:
                return value
        alone = re.compile(rf"^\s*{escaped}\s*[:\-–]?\s*$", re.IGNORECASE)
        for i in range(len(lines) - 1):
            if not alone.match(lines[i]):
                continue
            for j in range(i + 1, min(len(lines), i + 3)):
                value = lines[j].strip()
                if not value:
                    continue
                if len(value) < 150 and _heading_key(value) not in ALL_SECTION_HEADINGS:
                    return value
                break
    return None


