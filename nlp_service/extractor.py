def _as_name(candidate: str) -> Optional[str]:
    """The name in `candidate` when the whole text looks like a person's name, else None."""
    cleaned = re.sub(r"^[^\w]+", "", candidate.strip()).strip()
    # "Resume of Siti ...", "Curriculum Vitae - Siti ..." -> the name after it
    cleaned = re.sub(r"^(?:resume|curriculum vitae|cv)(?:\s+of)?\s*[:\-–]?\s*", "", cleaned, flags=re.IGNORECASE).strip()
    cleaned = _TITLE_BEFORE_NAME.sub("", cleaned)
    if not cleaned or len(cleaned) > 60:
        return None
    if re.search(r"[0-9@]", cleaned):
        return None
    if _heading_key(cleaned) in ALL_SECTION_HEADINGS:
        return None
    words = cleaned.split()
    if not (2 <= len(words) <= 5):
        return None
    # "a/l", "a/p", "s/o", "d/o" ("son/daughter of") are normal inside Malaysian names
    if not all(re.match(r"^(?:[A-Za-z][a-zA-Z.'\-]*|[asd]/[lpo])$", w, re.IGNORECASE) for w in words):
        return None
    # a name is written with capitals; only these small words stay lower-case inside it
    if any(w.lower() not in _NAME_PARTICLES and not re.match(r"^[A-Z]", w) for w in words):
        return None
    if any(w.lower().replace(".", "") in _NOT_NAME_WORDS for w in words):
        return None
    # a list of skills ("Python Java", "Microsoft Office", "Problem Solving") or a place is not a person
    if any(re.sub(r"[^a-z+#.]", "", w.lower()) in SKILL_WORDS for w in words):
        return None
    if cleaned.lower() in SKILL_PHRASES:
        return None
    if any(w.lower().replace(".", "") in _PLACE_WORDS for w in words):
        return None
    return cleaned


