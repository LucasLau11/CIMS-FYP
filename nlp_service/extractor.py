_REFERENCES_HEADING = re.compile(r"^(?:character\s+|professional\s+|academic\s+)?(?:references?|referees?)\s*[:\-–]?$", re.IGNORECASE)


def _before_references(text: str) -> str:
    """`text` without the References / Referees section at the end: the people named there (and their phone
    numbers) are not the candidate."""
    lines = text.split("\n")
    for i in range(5, len(lines)):
        if _REFERENCES_HEADING.match(lines[i].strip()):
            return "\n".join(lines[:i])
    return text


def _name_candidates(line: str) -> list[str]:
    """The whole line, then each part of "NAME | Job title", "NAME – Software Developer"."""
    parts = [p.strip() for p in re.split(r"\s*[|•·–—]\s*|\s+-\s+|\s+/\s+", line) if p.strip()]
    return [line, *parts] if len(parts) > 1 else [line]


def _looks_like_contact_or_role(line: str) -> bool:
    return (
        "@" in line
        or re.search(r"\d{3}[\s\-]?\d{3,4}", line) is not None
        or re.search(r"\b(?:student|undergraduate|graduate|developer|engineer|analyst|intern|designer|manager|programmer|executive)\b", line, re.IGNORECASE) is not None
    )


def _extract_name_regex(text: str) -> Optional[str]:
    body = _before_references(text)
    lines = [l.strip() for l in body.split("\n") if l.strip()]
    # what the skills section lists is never the name ("Python Java" can look like a two-word name)
    skill_keys = {s.lower() for s in _extract_skills(body)}
    skill_words = {w for k in skill_keys for w in k.split()}

    def ok(name: Optional[str]) -> Optional[str]:
        if name is None:
            return None
        low = name.lower()
        if low in skill_keys or all(w in skill_words for w in low.split()):
            return None
        return name

    # 1. an explicit "Name: ..." / "Full name: ..." line near the top is the most reliable
    for line in lines[:25]:
        m = re.match(r"^(?:full\s+)?name\s*[:\-–]\s*(.+)$", line, re.IGNORECASE)
        if m:
            name = ok(_as_name(m.group(1)))
            if name:
                return name
    # 2. the name is at the very top (after at most a title line such as "CURRICULUM VITAE" or a contact
    # line), sometimes followed by a job title on the same line ("LAU YIK HONG | Software Developer")
    for line in lines[:8]:
        if len(line) > 90:
            continue
        for part in _name_candidates(line):
            if len(part) > 60:
                continue
            name = ok(_as_name(part))
            if name:
                return name
    # 3. two-column templates put a sidebar (contact, skills) before the name in the extracted text: accept
    # a name-shaped line further down only when it is in capitals or sits next to a contact / job-title line
    for i in range(8, min(len(lines), 40)):
        line = lines[i]
        if len(line) > 60:
            continue
        name = ok(_as_name(line))
        if not name:
            continue
        near = any(0 <= k < len(lines) and _looks_like_contact_or_role(lines[k]) for k in (i - 1, i + 1))
        if line == line.upper() or near:
            return name
    return None


def _extract_name(text: str) -> tuple[Optional[str], str]:
    """Returns (name, source) — source is 'nlp' or 'regex' or 'none', kept
    for the FYP report's regex-vs-NLP comparison."""
    # The simple "first lines look like a name" rule goes first: measured on the fake-resume test it
    # is right far more often than the pretrained NER, which mistakes many Malaysian names for
    # organisations or places. The pretrained NER is only the fallback when the rule finds nothing.
    regex_name = _extract_name_regex(text)
    if regex_name:
        return regex_name, "regex"

    head_text = "\n".join(text.split("\n")[:8])
    doc = _nlp(head_text)
    for ent in doc.ents:
        candidate = ent.text.strip()
        if (ent.label_ == "PERSON" and 1 < len(candidate.split()) <= 5 and not _looks_like_a_place_not_a_name(candidate)
                and _as_name(candidate) is not None):
            return candidate, "nlp"
    return None, "none"


# a run of digits that might be a phone number: digits, spaces, hyphens and brackets, optionally after "+"
_PHONE_RUN = re.compile(r"(?<![\w@])(?:\+\s?)?\(?\d[\d\s\-()]{5,}\d(?![\w@])")


def _is_phone(candidate: str) -> bool:
    """True when `candidate` is written the way people write phone numbers in Malaysia (and, with a "+" country
    code, abroad): "+60 12-345 6789", "012-3456789", "03-1234 5678", "+65 9123 4567". A postcode (5 digits), an
    IC number, a date or a year range is not."""
    plus = candidate.lstrip().startswith("+")
    d = re.sub(r"\D", "", candidate)
    if not 9 <= len(d) <= 14:
        return False

    def national(n: str) -> bool:
        return re.fullmatch(r"1\d{8,9}", n) is not None or re.fullmatch(r"[3-9]\d{7,8}", n) is not None

    if plus:
        if d.startswith("60"):
            return national(d[2:])
        return not d.startswith("0")  # another country's number, written with its + code
    if d.startswith("60"):
        return len(d) >= 11 and national(d[2:])  # 60123456789
    if d.startswith("0"):
        return national(d[1:])  # 0123456789, 03-12345678
    return False


def _phone_in(line: str) -> Optional[str]:
    cleaned = line.replace("(+60)", "+60").replace("(+6)", "+6")
    for m in _PHONE_RUN.finditer(cleaned):
        # the run may hold a postcode or a year next to the number ("11900 012-345 6789"): try every stretch of
        # its space-separated groups, earliest start and longest first
        groups = m.group(0).strip().split()
        for i in range(len(groups)):
            for j in range(len(groups), i, -1):
                candidate = " ".join(groups[i:j])
                if _is_phone(candidate):
                    return candidate
    return None


def _extract_phone(text: str) -> Optional[str]:
    body = _before_references(text)
    labelled = _extract_labelled(
        body, ["phone number", "phone", "mobile no", "mobile", "contact no", "contact number", "tel", "h/p", "hp", "contact"]
    )
    if labelled:
        p = _phone_in(labelled)
        if p:
            return p
    for line in body.split("\n"):
        p = _phone_in(line)
        if p:
            return p
    return None


_MONTHS = {"jan": 1, "feb": 2, "mar": 3, "apr": 4, "may": 5, "jun": 6, "jul": 7, "aug": 8, "sep": 9, "oct": 10, "nov": 11, "dec": 12}


def _valid_date(year: int, month: int, day: int) -> Optional[str]:
    from datetime import date

    if year < 100:
        year += 1900 if year > 50 else 2000
    if year < 1940 or year > date.today().year:
        return None
    try:
        return date(year, month, day).isoformat()
    except ValueError:  # 31 February and the like
        return None


def _extract_dob(text: str) -> Optional[str]:
    label = re.search(
        r"(?:date\s+of\s+birth|d\.?\s?o\.?\s?b\.?|birth\s*date|birthday|born)\b\s*(?:on)?\s*[:\-–]?\s*(.{6,40})",
        text,
        re.IGNORECASE,
    )
    if not label:
        return None
    raw = label.group(1)

    m = re.search(r"(\d{4})[/\-.](\d{1,2})[/\-.](\d{1,2})", raw)  # 2002-03-12
    if m:
        return _valid_date(int(m.group(1)), int(m.group(2)), int(m.group(3)))
    m = re.search(r"(\d{1,2})[/\-.](\d{1,2})[/\-.](\d{2,4})", raw)  # 12/03/2002
    if m:
        return _valid_date(int(m.group(3)), int(m.group(2)), int(m.group(1)))
    m = re.search(r"(\d{1,2})(?:st|nd|rd|th)?\s+([A-Za-z]{3,9})\.?,?\s+(\d{4})", raw)  # 12th March 2002
    if m and m.group(2)[:3].lower() in _MONTHS:
        return _valid_date(int(m.group(3)), _MONTHS[m.group(2)[:3].lower()], int(m.group(1)))
    m = re.search(r"([A-Za-z]{3,9})\.?\s+(\d{1,2})(?:st|nd|rd|th)?,?\s+(\d{4})", raw)  # March 12, 2002
    if m and m.group(1)[:3].lower() in _MONTHS:
        return _valid_date(int(m.group(3)), _MONTHS[m.group(1)[:3].lower()], int(m.group(2)))
    return None


_POSTCODE = re.compile(r"\b\d{5}\b")


def _extract_address(text: str) -> Optional[str]:
    lines = text.split("\n")
    labelled = _extract_labelled(
        text,
        ["residential address", "home address", "current address", "permanent address", "correspondence address",
         "address", "residing at", "location"],
    )
    if labelled:
        # the address often continues on the next line ("Address: No. 12, Jalan X" / "50450 Kuala Lumpur")
        index = next((i for i, l in enumerate(lines) if labelled in l), -1)
        if index >= 0 and index + 1 < len(lines) and not _POSTCODE.search(labelled):
            nxt = lines[index + 1].strip()
            if (
                nxt
                and len(nxt) <= 90
                and ":" not in nxt
                and _heading_key(nxt) not in ALL_SECTION_HEADINGS
                and (_POSTCODE.search(nxt) or "," in nxt)
            ):
                return f"{labelled}, {nxt}"
        return labelled

    city_state_pattern = re.compile(r"^[A-Za-z\s]{3,30},\s*[A-Za-z\s]{2,30}$")
    for raw_line in lines:
        if not raw_line.strip() or len(raw_line) > 220:
            continue
        # a contact line may hold several things ("No. 2, Jalan X, 40000 Shah Alam  /  Tel 012...  /  a@b.com")
        for part in re.split(r"\s+/\s+|\s*[|•·]\s*|\s{3,}", raw_line):
            line = part.strip()
            if not line or len(line) > 150 or "@" in line:
                continue
            if _STREET_KEYWORDS.search(line) and _POSTCODE.search(line):
                return line
            if _STREET_KEYWORDS.search(line) and len(line) > 15:
                return line
    for line in [l.strip() for l in lines[:10]]:
        if city_state_pattern.match(line):
            return line
    return None


def _extract_programme(text: str) -> Optional[str]:
    labelled = _extract_labelled(text, ["programme", "program", "course", "field of study", "major"])
    if labelled:
        return labelled

    # a line naming a degree type even without a "Programme:" label, e.g.
    # "Bachelor of ... (Hons), TAR UMT, 2022-2025" or "Currently pursuing Bachelor of ... at TAR UMT."
    degree = re.search(
        r"\b((?:bachelor|diploma|master|foundation|certificate)\b[^,|\n]*?)(?=\s+(?:at|from|@)\s+|\s*[,|]|\.?\s*$|\n)",
        text,
        re.IGNORECASE | re.MULTILINE,
    )
    if not degree:
        return None
    line = degree.group(1).strip()
    return line if line and len(line) <= 150 else None


def _extract_semester(text: str) -> Optional[int]:
    for m in re.finditer(r"\bsem(?:ester)?\.?\s*[:\-]?\s*(\d{1,2})\b", text, re.IGNORECASE):
        value = int(m.group(1))
        if 1 <= value <= 4:  # the app offers semesters 1 to 4
            return value
    return None


_CGPA_LABEL = r"(?:c\.?g\.?p\.?a\.?|cumulative\s+(?:grade\s+point\s+average|gpa)|grade\s+point\s+average|gpa)"


def _extract_cgpa(text: str) -> Optional[float]:
    # CGPA: 3.45 / CGPA of 3.45 / CGPA (3.45) / GPA 3.45/4.0 ; and "3.45 CGPA" / "3.45/4.00 CGPA"
    after = re.compile(rf"\b{_CGPA_LABEL}[^\d\n]{{0,30}}?(\d\.\d{{1,2}})(?!\d)", re.IGNORECASE)
    before = re.compile(rf"(\d\.\d{{1,2}})\s*(?:/\s*4(?:\.0+)?\s*)?{_CGPA_LABEL}\b", re.IGNORECASE)
    for pattern in (after, before):
        for m in pattern.finditer(text):
            value = float(m.group(1))
            if 0 < value <= 4.0:
                return value
    return None


def _merge_skills(*groups: list[str], limit: int = 40) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for group in groups:
        for item in group:
            key = item.lower()
            if key not in seen:
                seen.add(key)
                out.append(item)
                if len(out) >= limit:
                    return out
    return out


def _extract_faculty(text: str) -> Optional[str]:
    """"Faculty: ..." or a line / bracket that says "Faculty of <name>"."""
    labelled = _extract_labelled(text, ["faculty"])
    if labelled:
        return labelled
    m = re.search(r"\b(Faculty of [A-Z][A-Za-z ,&]+?)(?=\)|\.|\n|$)", text, re.MULTILINE)
    return m.group(1).strip() if m else None


def parse(text: str, skills_mode: str = "auto") -> ParsedResumeData:
    """skills_mode: "section" = only the items under a Skills heading (the original behaviour),
    "model" = only what the trained SKILL model finds, "both" = the two combined, "auto" (default) =
    the Skills-heading rules first and, ONLY when they find nothing (a resume with no skills list),
    the trained model.

    Why "auto" is not "both": measured on the fake-resume test, the heading rules are already
    precise on resumes that have a skills list, and adding the model there only adds wrong
    skills. The model earns its place on resumes without a skills list, where the rules find nothing."""
    import skills_model

    section = _extract_skills(text) if skills_mode in ("section", "both", "auto") else []
    if skills_mode == "auto":
        model = skills_model.extract(text) if not section else []
    else:
        model = skills_model.extract(text) if skills_mode in ("model", "both") else []

    name, name_source = _extract_name(text)
    return ParsedResumeData(
        fullName=name,
        nameSource=name_source,
        phone=_extract_phone(text),
        address=_extract_address(text),
        dateOfBirth=_extract_dob(text),
        programme=_extract_programme(text),
        faculty=_extract_faculty(text),
        semester=_extract_semester(text),
        cgpa=_extract_cgpa(text),
        skills=_merge_skills(model, section),
        workExperience=_extract_work_experience(text),
    )
